import * as fs from 'node:fs';
import * as path from 'node:path';
import { parseEnvContent } from './parser.js';
import { scanCodebase } from './scanner.js';
import type { TypegenOptions } from './types.js';

function inferType(val: string): string {
  const trimmed = val.trim();
  if (trimmed === 'true' || trimmed === 'false') {
    return "'true' | 'false'";
  }
  if (/^-?\d+$/.test(trimmed)) {
    return 'string'; // process.env values in Node.js runtime are always strings
  }
  return 'string';
}

export function generateTypeScriptDeclarations(
  variables: Record<string, { value?: string; comment?: string; isVite?: boolean }>,
  options: { includeVite?: boolean } = {}
): string {
  const keys = Object.keys(variables).sort();

  const nodeFields: string[] = [];
  const viteFields: string[] = [];

  for (const key of keys) {
    const item = variables[key]!;
    const typeStr = item.value ? inferType(item.value) : 'string | undefined';
    const doc = item.comment ? `    /** ${item.comment} */\n` : '';

    nodeFields.push(`${doc}    ${key}?: ${typeStr};`);

    if (key.startsWith('VITE_') || item.isVite || options.includeVite) {
      viteFields.push(`${doc}    readonly ${key}: string;`);
    }
  }

  let code = `// Auto-generated by envguard (Agnet Software Corp.)
// Do not edit directly. Run 'npx envguard typegen' to regenerate.

declare global {
  namespace NodeJS {
    interface ProcessEnv {
${nodeFields.length > 0 ? nodeFields.join('\n') : '      [key: string]: string | undefined;'}
    }
  }
}
`;

  if (options.includeVite || viteFields.length > 0) {
    code += `
interface ImportMetaEnv {
${viteFields.length > 0 ? viteFields.join('\n') : '  readonly [key: string]: string;'}
}

interface ImportMeta {
  readonly env: ImportMetaEnv;
}
`;
  }

  code += `\nexport {};\n`;
  return code;
}

export function runTypegen(options: TypegenOptions = {}): {
  outputPath: string;
  variableCount: number;
  content: string;
} {
  const cwd = options.cwd || process.cwd();
  const envFilePath = options.envFile
    ? path.resolve(cwd, options.envFile)
    : path.resolve(cwd, '.env');
  const exampleFilePath = options.exampleFile
    ? path.resolve(cwd, options.exampleFile)
    : path.resolve(cwd, '.env.example');

  const mergedVars: Record<string, { value?: string; comment?: string; isVite?: boolean }> = {};

  // 1. Load from .env if exists
  if (fs.existsSync(envFilePath)) {
    try {
      const parsed = parseEnvContent(fs.readFileSync(envFilePath, 'utf-8'));
      for (const [k, v] of Object.entries(parsed)) {
        mergedVars[k] = { value: v.value, comment: v.comment, isVite: k.startsWith('VITE_') };
      }
    } catch {}
  }

  // 2. Supplement with .env.example
  if (fs.existsSync(exampleFilePath)) {
    try {
      const parsed = parseEnvContent(fs.readFileSync(exampleFilePath, 'utf-8'));
      for (const [k, v] of Object.entries(parsed)) {
        if (!mergedVars[k]) {
          mergedVars[k] = { value: v.value, comment: v.comment, isVite: k.startsWith('VITE_') };
        }
      }
    } catch {}
  }

  // 3. Supplement with code scan
  const scan = scanCodebase({ cwd, codePaths: options.codePaths });
  for (const ref of scan.references) {
    if (!mergedVars[ref.key]) {
      mergedVars[ref.key] = {
        value: undefined,
        comment: `Discovered in ${path.relative(cwd, ref.filePath)}`,
        isVite: ref.source === 'import.meta'
      };
    }
  }

  const hasVite = options.includeVite || Object.keys(mergedVars).some((k) => k.startsWith('VITE_'));
  const content = generateTypeScriptDeclarations(mergedVars, { includeVite: hasVite });

  const targetPath = options.outputPath
    ? path.resolve(cwd, options.outputPath)
    : path.resolve(cwd, 'env.d.ts');

  fs.writeFileSync(targetPath, content, 'utf-8');

  return {
    outputPath: targetPath,
    variableCount: Object.keys(mergedVars).length,
    content
  };
}
